"""Report generator tool: writes a structured Markdown report to the workspace.

Reports always go to ``<workspace>/reports/<filename>.md``. The filename is
restricted to letters, digits, ``-`` and ``_`` so the model cannot choose a path
outside that folder, and overwriting an existing report requires human approval.
"""

from __future__ import annotations

import os
from datetime import UTC, datetime
from pathlib import Path

from pydantic import BaseModel, Field

from app.tools.base import BaseTool, PermissionLevel, ToolContext, ToolError, ToolResult
from app.tools.filesystem import Workspace

REPORTS_DIR = "reports"


class ReportSection(BaseModel):
    heading: str = Field(min_length=1, max_length=200)
    body: str = Field(min_length=1, max_length=20_000, description="Markdown content.")


class ReportInput(BaseModel):
    title: str = Field(min_length=1, max_length=200)
    filename: str = Field(
        pattern=r"^[A-Za-z0-9][A-Za-z0-9_\-]{0,79}$",
        description="File name without extension, e.g. 'monthly_sales_june'.",
    )
    summary: str | None = Field(
        default=None, max_length=5000, description="Short executive summary (markdown)."
    )
    sections: list[ReportSection] = Field(min_length=1, max_length=30)


class ReportGeneratorTool(BaseTool):
    name = "report_generator"
    description = (
        "Save a finished Markdown report (title, optional executive summary and sections) "
        "to the workspace folder 'reports/'. Use it as the final step when the goal asks "
        "for a report. Overwriting an existing report requires human approval."
    )
    input_model = ReportInput
    permission = PermissionLevel.WRITE
    timeout_seconds = 10.0

    def __init__(self, workspace_dir: Path, max_bytes: int) -> None:
        self.workspace = Workspace(workspace_dir)
        self.max_bytes = max_bytes

    def target(self, params: ReportInput) -> Path:
        return self.workspace.resolve(f"{REPORTS_DIR}/{params.filename}.md")

    def approval_reason(self, args: BaseModel) -> str | None:
        params = self.typed(args, ReportInput)
        if self.target(params).exists():
            return f"This would overwrite the existing report '{REPORTS_DIR}/{params.filename}.md'."
        return None

    async def execute(self, args: BaseModel, context: ToolContext) -> ToolResult:
        params = self.typed(args, ReportInput)
        text = render(params, generated_at=datetime.now(UTC))
        encoded = text.encode("utf-8")
        if len(encoded) > self.max_bytes:
            raise ToolError("Report exceeds the configured file size limit")
        target = self.target(params)
        target.parent.mkdir(parents=True, exist_ok=True)
        tmp = target.with_name(f".{target.name}.tmp")
        tmp.write_bytes(encoded)
        os.replace(tmp, target)  # atomic: readers never see a half-written report
        rel = self.workspace.relative(target)
        return ToolResult(
            content=f"Saved report '{params.title}' to {rel} ({len(encoded):,} bytes)",
            data={"path": rel, "bytes": len(encoded), "sections": len(params.sections)},
        )


def render(params: ReportInput, generated_at: datetime) -> str:
    lines = [
        f"# {params.title.strip()}",
        "",
        f"_Generated by Dot Lab on {generated_at:%Y-%m-%d %H:%M} UTC_",
        "",
    ]
    if params.summary:
        lines += ["## Summary", "", params.summary.strip(), ""]
    for section in params.sections:
        lines += [f"## {section.heading.strip()}", "", section.body.strip(), ""]
    return "\n".join(lines).rstrip() + "\n"
